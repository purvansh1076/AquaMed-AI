"""
AquaMediAI — ML Trainer
========================

Trains two water-demand prediction models on the synthetic agronomic dataset:

    A. Random Forest  — baseline (scikit-learn)
    B. XGBoost        — primary model

IMPORTANT ACADEMIC DISCLAIMER
------------------------------
The dataset used here is **completely synthetic**.
It is generated by ``SyntheticDataGenerator`` using the FAO-56 single
crop-coefficient method (ET₀ × Kc × area).  No real farmer water-usage
records are used.  Metrics reported below are computed on the held-out
**test** split and reflect model fit to the synthetic signal only.

Pipeline
--------
    SyntheticDataGenerator.generate_dataset()
          │
          ▼
    train_val_test_split()          (70 / 15 / 15, stratified)
          │
          ├─► fit_encoders(train)   (NO leakage: fitted on train only)
          │
          ├─► engineer_features()  applied independently to each split
          │
          ├─► RandomForestRegressor.fit(X_train, y_train)
          ├─► XGBRegressor.fit(X_train, y_train, eval_set=[(X_val, y_val)])
          │
          └─► evaluate() on X_test, y_test → MAE, RMSE, R²

Persistence
-----------
All artefacts are saved under ``data/models/`` via joblib:
    rf_model.joblib          — trained RandomForestRegressor
    xgb_model.joblib         — trained XGBRegressor
    encoders.joblib          — FittedEncoders (must match inference)
    evaluation_results.json  — metric dict (not fabricated)
"""

from __future__ import annotations

import json
import logging
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from xgboost import XGBRegressor

from app.ml.data_generator import SyntheticDataGenerator
from app.ml.feature_engineering import (
    ENGINEERED_FEATURE_COLS,
    TARGET_COL,
    FittedEncoders,
    engineer_features,
    fit_encoders,
    get_feature_matrix,
    train_val_test_split,
    validate_dataframe,
)

logger = logging.getLogger(__name__)

# ─── Artefact file names ──────────────────────────────────────────────────────
RF_MODEL_FILE = "rf_model.joblib"
XGB_MODEL_FILE = "xgb_model.joblib"
ENCODERS_FILE = "encoders.joblib"
EVAL_RESULTS_FILE = "evaluation_results.json"
MODEL_VERSION = "1.0.0"


@dataclass
class ModelMetrics:
    """
    Evaluation metrics for a single model on a single split.
    All values come from actual model predictions — never fabricated.
    """

    mae: float          # Mean Absolute Error  (m³/day)
    rmse: float         # Root Mean Squared Error (m³/day)
    r2: float           # Coefficient of Determination
    n_samples: int      # Number of test samples evaluated
    split: str = "test" # Which split (train/val/test)

    def as_dict(self) -> Dict[str, Any]:
        return asdict(self)

    def __str__(self) -> str:
        return (
            f"MAE={self.mae:.4f}  RMSE={self.rmse:.4f}  R²={self.r2:.4f}"
            f"  (n={self.n_samples}, split={self.split})"
        )


@dataclass
class ModelResult:
    """
    Full training result for one model, including metrics on all three splits.

    Attributes
    ----------
    model_name : str
        Human-readable model identifier.
    model_version : str
        Semantic version string.
    train_metrics : ModelMetrics
        Metrics evaluated on the training set.
    val_metrics : ModelMetrics
        Metrics evaluated on the validation set.
    test_metrics : ModelMetrics
        Metrics evaluated on the held-out test set (primary reporting metric).
    training_time_seconds : float
        Wall-clock seconds for model.fit().
    n_features : int
        Number of input features.
    feature_columns : list of str
        Ordered list of feature column names.
    model_file : str
        Filename of the persisted model artefact.
    """

    model_name: str
    model_version: str = MODEL_VERSION
    train_metrics: Optional[ModelMetrics] = None
    val_metrics: Optional[ModelMetrics] = None
    test_metrics: Optional[ModelMetrics] = None
    training_time_seconds: float = 0.0
    n_features: int = 0
    feature_columns: List[str] = field(default_factory=list)
    model_file: str = ""

    def as_dict(self) -> Dict[str, Any]:
        d = {
            "model_name": self.model_name,
            "model_version": self.model_version,
            "training_time_seconds": round(self.training_time_seconds, 4),
            "n_features": self.n_features,
            "feature_columns": self.feature_columns,
            "model_file": self.model_file,
        }
        for split_attr in ("train_metrics", "val_metrics", "test_metrics"):
            m = getattr(self, split_attr)
            d[split_attr] = m.as_dict() if m else None
        return d


@dataclass
class TrainingArtifacts:
    """
    Container for everything produced by a full training run.
    Used by predictor.py and explainer.py to load the correct objects.
    """

    rf_result: ModelResult
    xgb_result: ModelResult
    encoders: FittedEncoders
    feature_columns: List[str]
    best_model_name: str          # 'RandomForest' or 'XGBoost'  (by test MAE)
    dataset_summary: Dict[str, Any]


# ─── Training hyperparameters ─────────────────────────────────────────────────
# These are deliberately modest for fast academic runs.
# Increase n_estimators / n_jobs for production use.

RF_PARAMS: Dict[str, Any] = {
    "n_estimators": 200,
    "max_depth": 15,
    "min_samples_leaf": 2,
    "n_jobs": -1,
    "random_state": 42,
}

XGB_PARAMS: Dict[str, Any] = {
    "n_estimators": 300,
    "learning_rate": 0.05,
    "max_depth": 6,
    "subsample": 0.8,
    "colsample_bytree": 0.8,
    "reg_alpha": 0.1,
    "reg_lambda": 1.0,
    "random_state": 42,
    "verbosity": 0,
    "n_jobs": -1,
    "early_stopping_rounds": 20,
    "eval_metric": "rmse",
}


# ─── Metric computation ───────────────────────────────────────────────────────

def compute_metrics(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    split: str = "test",
) -> ModelMetrics:
    """
    Compute regression metrics from actual predictions.

    Parameters
    ----------
    y_true : np.ndarray
        Ground-truth target values.
    y_pred : np.ndarray
        Model predictions.
    split : str
        Label for the split being evaluated.

    Returns
    -------
    ModelMetrics
    """
    mae = float(mean_absolute_error(y_true, y_pred))
    rmse = float(np.sqrt(mean_squared_error(y_true, y_pred)))
    r2 = float(r2_score(y_true, y_pred))
    return ModelMetrics(mae=mae, rmse=rmse, r2=r2, n_samples=len(y_true), split=split)


# ─── Training functions ───────────────────────────────────────────────────────

def train_random_forest(
    X_train: np.ndarray,
    y_train: np.ndarray,
    params: Optional[Dict[str, Any]] = None,
) -> Tuple[RandomForestRegressor, float]:
    """
    Train a RandomForestRegressor baseline.

    Parameters
    ----------
    X_train, y_train : arrays
        Training features and target.
    params : dict, optional
        Hyperparameter overrides. Defaults to RF_PARAMS.

    Returns
    -------
    (fitted_model, training_time_seconds)
    """
    p = {**RF_PARAMS, **(params or {})}
    model = RandomForestRegressor(**p)
    logger.info("Training RandomForest (n_estimators=%d)…", p["n_estimators"])
    t0 = time.perf_counter()
    model.fit(X_train, y_train)
    elapsed = time.perf_counter() - t0
    logger.info("RandomForest trained in %.2fs", elapsed)
    return model, elapsed


def train_xgboost(
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_val: np.ndarray,
    y_val: np.ndarray,
    params: Optional[Dict[str, Any]] = None,
) -> Tuple[XGBRegressor, float]:
    """
    Train an XGBRegressor with early stopping on the validation set.

    Parameters
    ----------
    X_train, y_train : arrays
        Training features and target.
    X_val, y_val : arrays
        Validation features and target (used for early stopping only).
    params : dict, optional
        Hyperparameter overrides. Defaults to XGB_PARAMS.

    Returns
    -------
    (fitted_model, training_time_seconds)
    """
    p = {**XGB_PARAMS, **(params or {})}
    model = XGBRegressor(**p)
    logger.info(
        "Training XGBoost (n_estimators=%d, lr=%.3f, early_stop=%d)…",
        p["n_estimators"],
        p["learning_rate"],
        p.get("early_stopping_rounds", 0),
    )
    t0 = time.perf_counter()
    model.fit(
        X_train,
        y_train,
        eval_set=[(X_val, y_val)],
        verbose=False,
    )
    elapsed = time.perf_counter() - t0
    best_iter = getattr(model, "best_iteration", p["n_estimators"])
    logger.info("XGBoost trained in %.2fs (best iteration: %d)", elapsed, best_iter)
    return model, elapsed


# ─── Main training pipeline ───────────────────────────────────────────────────

def run_training_pipeline(
    n_samples: int = 3000,
    seed: int = 42,
    model_dir: Optional[Path] = None,
    save_artifacts: bool = True,
    rf_params: Optional[Dict[str, Any]] = None,
    xgb_params: Optional[Dict[str, Any]] = None,
) -> TrainingArtifacts:
    """
    Execute the full ML training pipeline end-to-end.

    Steps
    -----
    1. Generate synthetic dataset (FAO-56 grounded, labelled as synthetic).
    2. Validate dataset integrity.
    3. Train/val/test split (70/15/15, stratified by scenario_type).
    4. Fit encoders on training data only (no leakage).
    5. Apply feature engineering to all splits.
    6. Train RandomForest baseline.
    7. Train XGBoost with early stopping.
    8. Evaluate both models on train, val, and test splits.
    9. Persist models, encoders, and metrics.

    Parameters
    ----------
    n_samples : int
        Number of synthetic samples to generate.
    seed : int
        Random seed for reproducibility.
    model_dir : Path, optional
        Directory for saving model artefacts. Defaults to ``data/models``.
    save_artifacts : bool
        Whether to persist models and metrics to disk.
    rf_params : dict, optional
        RandomForest hyperparameter overrides.
    xgb_params : dict, optional
        XGBoost hyperparameter overrides.

    Returns
    -------
    TrainingArtifacts
        Container with results, trained models, and encoders.
    """
    model_dir = model_dir or Path("data/models")
    model_dir.mkdir(parents=True, exist_ok=True)

    # ── Step 1: Generate synthetic dataset ────────────────────────────────────
    logger.info("Generating synthetic agronomic dataset (n=%d, seed=%d)…", n_samples, seed)
    gen = SyntheticDataGenerator(seed=seed)
    df = gen.generate_dataset(n_samples=n_samples)

    # ── Step 2: Validate ──────────────────────────────────────────────────────
    errors = validate_dataframe(df)
    if errors:
        raise ValueError(f"Dataset validation failed: {errors}")
    logger.info("Dataset validation passed (%d rows).", len(df))

    # ── Step 3: Split ─────────────────────────────────────────────────────────
    train_df, val_df, test_df = train_val_test_split(df, seed=seed)
    logger.info(
        "Dataset split -> train=%d  val=%d  test=%d", len(train_df), len(val_df), len(test_df)
    )

    # ── Step 4: Fit encoders on training data only ────────────────────────────
    logger.info("Fitting encoders on training split only…")
    encoders = fit_encoders(train_df)

    # ── Step 5: Feature engineering ───────────────────────────────────────────
    train_eng = engineer_features(train_df, encoders)
    val_eng = engineer_features(val_df, encoders)
    test_eng = engineer_features(test_df, encoders)

    X_train, y_train = get_feature_matrix(train_eng)
    X_val, y_val = get_feature_matrix(val_eng)
    X_test, y_test = get_feature_matrix(test_eng)

    n_features = X_train.shape[1]
    logger.info("Feature matrix: %d features, %d train samples", n_features, len(X_train))

    # ── Step 6: Train RandomForest ────────────────────────────────────────────
    rf_model, rf_time = train_random_forest(X_train, y_train, params=rf_params)

    rf_train_m = compute_metrics(y_train, rf_model.predict(X_train), "train")
    rf_val_m = compute_metrics(y_val, rf_model.predict(X_val), "val")
    rf_test_m = compute_metrics(y_test, rf_model.predict(X_test), "test")

    logger.info("RandomForest — Train: %s", rf_train_m)
    logger.info("RandomForest — Val:   %s", rf_val_m)
    logger.info("RandomForest — Test:  %s", rf_test_m)

    rf_result = ModelResult(
        model_name="RandomForest",
        train_metrics=rf_train_m,
        val_metrics=rf_val_m,
        test_metrics=rf_test_m,
        training_time_seconds=rf_time,
        n_features=n_features,
        feature_columns=ENGINEERED_FEATURE_COLS,
        model_file=RF_MODEL_FILE,
    )

    # ── Step 7: Train XGBoost ─────────────────────────────────────────────────
    xgb_model, xgb_time = train_xgboost(
        X_train, y_train, X_val, y_val, params=xgb_params
    )

    xgb_train_m = compute_metrics(y_train, xgb_model.predict(X_train), "train")
    xgb_val_m = compute_metrics(y_val, xgb_model.predict(X_val), "val")
    xgb_test_m = compute_metrics(y_test, xgb_model.predict(X_test), "test")

    logger.info("XGBoost — Train: %s", xgb_train_m)
    logger.info("XGBoost — Val:   %s", xgb_val_m)
    logger.info("XGBoost — Test:  %s", xgb_test_m)

    xgb_result = ModelResult(
        model_name="XGBoost",
        train_metrics=xgb_train_m,
        val_metrics=xgb_val_m,
        test_metrics=xgb_test_m,
        training_time_seconds=xgb_time,
        n_features=n_features,
        feature_columns=ENGINEERED_FEATURE_COLS,
        model_file=XGB_MODEL_FILE,
    )

    # ── Step 8: Best model by test MAE ────────────────────────────────────────
    best_model_name = (
        "XGBoost"
        if xgb_result.test_metrics.mae <= rf_result.test_metrics.mae
        else "RandomForest"
    )
    logger.info(
        "Best model (by test MAE): %s  (RF=%.4f, XGB=%.4f)",
        best_model_name,
        rf_result.test_metrics.mae,
        xgb_result.test_metrics.mae,
    )

    # ── Step 9: Persist artefacts ─────────────────────────────────────────────
    dataset_summary = {
        "n_total": len(df),
        "n_train": len(train_df),
        "n_val": len(val_df),
        "n_test": len(test_df),
        "n_features": n_features,
        "feature_columns": ENGINEERED_FEATURE_COLS,
        "target_column": TARGET_COL,
        "seed": seed,
        "scenario_distribution": df["scenario_type"].value_counts().to_dict(),
        "data_disclaimer": (
            "SYNTHETIC DATA — All records generated algorithmically using the "
            "FAO-56 ET₀ × Kc × area method. No real farmer data."
        ),
    }

    if save_artifacts:
        _save_artifacts(
            model_dir=model_dir,
            rf_model=rf_model,
            xgb_model=xgb_model,
            encoders=encoders,
            rf_result=rf_result,
            xgb_result=xgb_result,
            best_model_name=best_model_name,
            dataset_summary=dataset_summary,
        )

    return TrainingArtifacts(
        rf_result=rf_result,
        xgb_result=xgb_result,
        encoders=encoders,
        feature_columns=ENGINEERED_FEATURE_COLS,
        best_model_name=best_model_name,
        dataset_summary=dataset_summary,
    )


def _save_artifacts(
    model_dir: Path,
    rf_model: RandomForestRegressor,
    xgb_model: XGBRegressor,
    encoders: FittedEncoders,
    rf_result: ModelResult,
    xgb_result: ModelResult,
    best_model_name: str,
    dataset_summary: Dict[str, Any],
) -> None:
    """Persist all training artefacts to ``model_dir``."""
    joblib.dump(rf_model, model_dir / RF_MODEL_FILE)
    logger.info("Saved RandomForest -> %s", model_dir / RF_MODEL_FILE)

    joblib.dump(xgb_model, model_dir / XGB_MODEL_FILE)
    logger.info("Saved XGBoost -> %s", model_dir / XGB_MODEL_FILE)

    joblib.dump(encoders, model_dir / ENCODERS_FILE)
    logger.info("Saved encoders -> %s", model_dir / ENCODERS_FILE)

    eval_results = {
        "best_model": best_model_name,
        "model_version": MODEL_VERSION,
        "RandomForest": rf_result.as_dict(),
        "XGBoost": xgb_result.as_dict(),
        "dataset": dataset_summary,
    }
    eval_path = model_dir / EVAL_RESULTS_FILE
    with open(eval_path, "w", encoding="utf-8") as f:
        json.dump(eval_results, f, indent=2)
    logger.info("Saved evaluation results -> %s", eval_path)


# ─── Load helpers ─────────────────────────────────────────────────────────────

def load_model(model_dir: Path, model_name: str = "XGBoost") -> Any:
    """
    Load a persisted model from disk.

    Parameters
    ----------
    model_dir : Path
        Directory containing model .joblib and encoders.joblib.
    model_name : str
        'XGBoost' or 'RandomForest'.

    Returns
    -------
    Fitted model object.
    """
    file_map = {"XGBoost": XGB_MODEL_FILE, "RandomForest": RF_MODEL_FILE}
    if model_name not in file_map:
        raise ValueError(f"Unknown model_name: {model_name!r}. Choose from {list(file_map)}")
    path = model_dir / file_map[model_name]
    if not path.exists():
        raise FileNotFoundError(
            f"Model artefact not found: {path}. "
            "Run 'python scripts/train_models.py' first."
        )
    model = joblib.load(path)
    logger.info("Loaded %s from %s", model_name, path)
    return model


FILE_MAP: Dict[str, str] = {"XGBoost": XGB_MODEL_FILE, "RandomForest": RF_MODEL_FILE}


def validate_artifacts(model_dir: Path) -> bool:
    """
    Validate that all required model artefacts exist and are consistent.

    Checks:
    - model .joblib files exist
    - encoders .joblib file exists
    - evaluation_results.json exists and is valid
    - best_model field references an existing model file

    Parameters
    ----------
    model_dir : Path
        Directory containing model artefacts.

    Returns
    -------
    bool
        True if all artefacts are valid.

    Raises
    ------
    FileNotFoundError
        If any required artefact is missing.
    ValueError
        If artefacts are internally inconsistent.
    """
    errors: List[str] = []

    # Check model files
    for model_name, fname in [("XGBoost", XGB_MODEL_FILE), ("RandomForest", RF_MODEL_FILE)]:
        p = model_dir / fname
        if not p.exists():
            errors.append(f"Missing model artefact: {p}")
        else:
            logger.debug("Model artefact present: %s", p)

    # Check encoders
    enc_path = model_dir / ENCODERS_FILE
    if not enc_path.exists():
        errors.append(f"Missing encoders artefact: {enc_path}")
    else:
        logger.debug("Encoders artefact present: %s", enc_path)

    # Check evaluation results
    eval_path = model_dir / EVAL_RESULTS_FILE
    if not eval_path.exists():
        errors.append(f"Missing evaluation results: {eval_path}")
    else:
        try:
            with open(eval_path, encoding="utf-8") as f:
                data = json.load(f)
            if "best_model" not in data:
                errors.append("evaluation_results.json missing 'best_model' field")
            elif data["best_model"] not in ("XGBoost", "RandomForest"):
                errors.append(f"evaluation_results.json 'best_model'='{data['best_model']}' is not a recognized model")
            else:
                best_fp = model_dir / FILE_MAP[data["best_model"]]
                if not best_fp.exists():
                    errors.append(f"best_model='{data['best_model']}' references missing file: {best_fp}")
        except (json.JSONDecodeError, KeyError) as e:
            errors.append(f"evaluation_results.json is not valid JSON: {e}")

    if errors:
        raise ValueError("Artifact validation failed:\n  " + "\n  ".join(errors))
    return True


def load_encoders(model_dir: Path) -> FittedEncoders:
    """
    Load the persisted FittedEncoders from disk.

    Parameters
    ----------
    model_dir : Path
        Directory containing model artefacts.

    Returns
    -------
    FittedEncoders
    """
    path = model_dir / ENCODERS_FILE
    if not path.exists():
        raise FileNotFoundError(
            f"Encoders artefact not found: {path}. "
            "Run 'python scripts/train_models.py' first."
        )
    encoders = joblib.load(path)
    logger.info("Loaded encoders from %s", path)
    return encoders


def load_evaluation_results(model_dir: Path) -> Dict[str, Any]:
    """Load the saved evaluation metrics JSON."""
    path = model_dir / EVAL_RESULTS_FILE
    if not path.exists():
        raise FileNotFoundError(f"Evaluation results not found: {path}")
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def validate_and_load_artifacts(model_dir: Path) -> Tuple[Any, FittedEncoders, Dict[str, Any]]:
    """
    Convenience: validate artifacts exist and are consistent, then load them.

    Returns
    -------
    (model, encoders, eval_results) tuple ready for predictor construction.
    """
    validate_artifacts(model_dir)
    model = load_model(model_dir, model_name="XGBoost")
    encoders = load_encoders(model_dir)
    eval_results = load_evaluation_results(model_dir)
    return model, encoders, eval_results
